"""Command-line interface for the KV260 PYNQ renderer."""

import argparse

from .app import RenderApplication
from .config import (
    DEFAULT_BITSTREAM,
    DEFAULT_GRID_MAX,
    DEFAULT_GRID_MIN,
    DEFAULT_HWH,
    DEFAULT_MEM_DIR,
    DEFAULT_TRACE_ROI,
    DMA_NAME,
    FRAME_HEIGHT,
    FRAME_WIDTH,
    IP_NAME,
    MAX_BATCH_RAYS,
)


def build_parser():
    parser = argparse.ArgumentParser(description="Run SDF-RT on a KV260 with PYNQ")
    parser.add_argument("--bitstream", default=str(DEFAULT_BITSTREAM))
    parser.add_argument(
        "--hwh",
        default=str(DEFAULT_HWH),
        help="HWH metadata for overlay/IP discovery; fpga_top offsets follow the RTL wrapper",
    )
    parser.add_argument("--ip-name", default=IP_NAME)
    parser.add_argument("--dma-name", default=DMA_NAME)
    parser.add_argument("--mem-dir", default=str(DEFAULT_MEM_DIR))
    parser.add_argument("--width", type=int, default=FRAME_WIDTH)
    parser.add_argument("--height", type=int, default=FRAME_HEIGHT)
    parser.add_argument("--batch-rays", type=int, default=MAX_BATCH_RAYS)
    parser.add_argument("--frames", type=int, default=180)
    parser.add_argument(
        "--rotation-period-frames",
        type=int,
        default=180,
        help="orbit-camera frames per 360-degree turn; use 0 for a static camera",
    )
    parser.add_argument("--no-prepack-rays", action="store_true")
    parser.add_argument("--verbose-ray-progress", action="store_true")
    parser.add_argument(
        "--validate-result-stream",
        action="store_true",
        help="enable duplicate/missing RayID checks in the native G-buffer path",
    )
    parser.add_argument("--origin", nargs=3, type=float, default=None)
    parser.add_argument("--grid-min", nargs=3, type=float, default=DEFAULT_GRID_MIN)
    parser.add_argument("--grid-max", nargs=3, type=float, default=DEFAULT_GRID_MAX)
    parser.add_argument("--skip-sdf-init", action="store_true")
    parser.add_argument("--sdf-timeout", type=float, default=10.0)
    parser.add_argument("--setup-timeout", type=float, default=2.0)
    parser.add_argument("--batch-timeout", type=float, default=30.0)
    parser.add_argument(
        "--hold-display",
        action="store_true",
        help="keep the DisplayPort process alive after rendering until interrupted",
    )
    parser.add_argument(
        "--display-hold-seconds",
        type=float,
        default=3.0,
        help="keep the final synchronized HDMI frame active before shutdown",
    )
    parser.add_argument("--display-width", type=int, default=1024)
    parser.add_argument("--display-height", type=int, default=768)
    parser.add_argument(
        "--render-data",
        default=None,
        help="PYNQ render sidecar generated by make sim; defaults to <mem-dir>/pynq_render_data.bin",
    )
    parser.add_argument(
        "--render-threads",
        type=int,
        default=4,
        help="OpenMP threads used by the native normal G-buffer builder",
    )
    roi_group = parser.add_mutually_exclusive_group()
    roi_group.add_argument(
        "--trace-roi", nargs=4, type=int,
        metavar=("X", "Y", "WIDTH", "HEIGHT"), default=None,
        help="4x4-aligned intersection/G-buffer ROI",
    )
    roi_group.add_argument("--full-frame", action="store_true")
    return parser


def validate_args(parser, args):
    if args.width <= 0 or args.height <= 0:
        parser.error("width and height must be positive")
    if not 1 <= args.batch_rays <= MAX_BATCH_RAYS:
        parser.error(f"batch-rays must be in 1..{MAX_BATCH_RAYS}")
    if args.frames <= 0:
        parser.error("frames must be positive")
    if args.rotation_period_frames < 0:
        parser.error("rotation-period-frames must be non-negative")
    if args.render_threads <= 0:
        parser.error("render-threads must be positive")
    if args.display_width <= 0 or args.display_height <= 0:
        parser.error("display dimensions must be positive")
    if args.display_hold_seconds < 0.0:
        parser.error("display-hold-seconds must be non-negative")
    if args.display_width > args.width or args.display_height > args.height:
        parser.error("direct scanout output must fit inside the render dimensions")
    if args.full_frame:
        args.trace_roi = (0, 0, args.width, args.height)
    elif args.trace_roi is None:
        args.trace_roi = (
            DEFAULT_TRACE_ROI
            if (args.width, args.height) == (FRAME_WIDTH, FRAME_HEIGHT)
            else (0, 0, args.width, args.height)
        )
    x, y, roi_width, roi_height = args.trace_roi
    if x < 0 or y < 0 or roi_width <= 0 or roi_height <= 0:
        parser.error("trace-roi must have positive dimensions and non-negative origin")
    if x + roi_width > args.width or y + roi_height > args.height:
        parser.error("trace-roi must fit inside the render dimensions")
    if any(value % 4 for value in args.trace_roi):
        parser.error("trace-roi must be aligned to 4x4 Trace blocks")


def main(argv=None):
    parser = build_parser()
    args = parser.parse_args(argv)
    validate_args(parser, args)
    RenderApplication(args).run()
